'use strict';

const fs = require( 'node:fs' );
const path = require( 'node:path' );

const projectRoot = path.resolve( __dirname, '..' );
const dompurifyDirectory = path.join( projectRoot, 'node_modules', 'dompurify' );
const vendorDirectory = path.join( projectRoot, 'js', 'vendor', 'dompurify' );
const packageFile = path.join( dompurifyDirectory, 'package.json' );
const licenseFile = path.join( dompurifyDirectory, 'LICENSE' );
const versionFile = path.join( vendorDirectory, 'version.php' );
const runtimeFiles = [
	'purify.js',
	'purify.js.map',
	'purify.min.js',
	'purify.min.js.map'
];
const assetFiles = runtimeFiles.map( ( filename ) => path.join( dompurifyDirectory, 'dist', filename ) );

for ( const file of [ packageFile, licenseFile, ...assetFiles ] ) {
	if ( ! fs.existsSync( file ) ) {
		throw new Error( `Missing DOMPurify build input: ${ file }` );
	}
}

const dompurifyPackage = JSON.parse( fs.readFileSync( packageFile, 'utf8' ) );
const version = dompurifyPackage.version;

if ( typeof version !== 'string' || ! /^[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/.test( version ) ) {
	throw new Error( `Invalid DOMPurify package version: ${ version }` );
}

fs.mkdirSync( vendorDirectory, { recursive: true } );
for ( const assetFile of assetFiles ) {
	fs.copyFileSync( assetFile, path.join( vendorDirectory, path.basename( assetFile ) ) );
}
fs.copyFileSync( licenseFile, path.join( vendorDirectory, 'LICENSE' ) );
fs.writeFileSync(
	versionFile,
	`<?php\n/**\n * Generated by npm run sync:dompurify. Do not edit manually.\n *\n * @package JDITC\\Add_Wordfence_2FA_to_Ultimate_Member\n */\n\nreturn '${ version }';\n`
);

console.log( `Synced DOMPurify ${ version }.` );
